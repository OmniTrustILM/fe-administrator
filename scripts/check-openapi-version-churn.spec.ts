import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

// @ts-expect-error - plain ESM build script, no type declarations
import { run } from './check-openapi-version-churn.mjs';

type FakeGenerator = { versionInHeader?: boolean; versionInModel?: boolean; ignoresSchema?: boolean };

function fakeExec({ versionInHeader = false, versionInModel = false, ignoresSchema = false }: FakeGenerator = {}) {
    return vi.fn((command: string, args: string[]) => {
        if (path.basename(command) !== 'openapi-generator-cli') return;
        const tools = JSON.parse(readFileSync(args[args.indexOf('--openapitools') + 1], 'utf8'));
        const { inputSpec, output } = tools['generator-cli'].generators['typescript-rxjs-local'];
        const spec = readFileSync(inputSpec, 'utf8');
        const version = /^ {2}version: (.*)$/m.exec(spec)?.[1] ?? '';
        const versionLine = versionInHeader ? ` * The version of the OpenAPI document: ${version}\n` : '';
        const serialNumber = spec.includes('serialNumber') && !ignoresSchema ? '    serialNumber?: string;\n' : '';
        const stamp = versionInModel ? `export const VERSION = '${version}';\n` : '';

        mkdirSync(path.join(output, 'models'), { recursive: true });
        mkdirSync(path.join(output, '.openapi-generator'), { recursive: true });
        writeFileSync(path.join(output, 'API_VERSION'), `${version}\n`);
        writeFileSync(path.join(output, '.openapi-generator', 'FILES'), '.gitignore\nAPI_VERSION\nmodels/WidgetDto.ts\n');
        writeFileSync(
            path.join(output, 'models', 'WidgetDto.ts'),
            `// tslint:disable
/**
 * Core API
 * REST API for ILM Core
 *
${versionLine} * Contact: info@otilm.com
 *
 * NOTE: This class is auto generated by OpenAPI Generator (https://openapi-generator.tech).
 * https://openapi-generator.tech
 * Do not edit the class manually.
 */

${stamp}export interface WidgetDto {
    uuid: string;
    name: string;
${serialNumber}}
`,
        );
    });
}

describe('check-openapi-version-churn run', () => {
    beforeEach(() => {
        vi.spyOn(console, 'log').mockImplementation(() => {});
    });

    afterEach(() => {
        vi.restoreAllMocks();
    });

    it('passes when a version bump only changes API_VERSION', () => {
        const exec = fakeExec();
        expect(() => run(exec)).not.toThrow();
        expect(exec).toHaveBeenCalledWith(
            expect.stringMatching(/biome$/),
            expect.arrayContaining(['format', '--write']),
            expect.anything(),
        );
    });

    it('fails when the generated header still carries the API version', () => {
        expect(() => run(fakeExec({ versionInHeader: true }))).toThrow('models/WidgetDto.ts still carries the API version in its header');
    });

    it('fails when a version bump changes a generated TypeScript file', () => {
        expect(() => run(fakeExec({ versionInModel: true }))).toThrow('a version-only bump must change API_VERSION and nothing else');
    });

    it('fails when a schema change does not reach the generated model', () => {
        expect(() => run(fakeExec({ ignoresSchema: true }))).toThrow('a schema change must reach the generated model');
    });
});
